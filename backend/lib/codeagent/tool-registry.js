/**
 * The single gate. Returns a result for every input, including the bad
 * ones — see the header for why it must not throw.
 */
async function dispatch(name, rawArgs, ctx) {
    const entry = byName(name);
    // Same wording the old chain used, so nothing downstream has to change.
    if (!entry)
        return { ok: false, content: "Unknown tool: " + name };
    /* THE GATE. Asked before the arguments are even looked at, because a
       write in plan mode is refused whether or not its arguments were
       valid — and because this is the check the schema filter could only
       pretend to make. */
    if (!agentState.permits(ctx.mode, entry.name)) {
        return { ok: false, content: agentState.denialMessage(ctx.mode, entry.name) };
    }
    const args = rawArgs && typeof rawArgs === "object" ? rawArgs : {};
    try {
        if (entry.validate)
            entry.validate(args, ctx);
        return await entry.run(args, ctx);
    }
    catch (e) {
        const message = e instanceof Error ? e.message : String(e);
        return { ok: false, content: "Error: " + message };
    }
}
/**
 * Trim a turn's results to a whole-turn budget, in call order.
 *
 * Applied after the batch rather than inside each tool, because no tool
 * can know what its siblings returned. Errors are never trimmed: they
 * are short, and they are the most load-bearing text in the request.
 */
function applyTurnBudget(results, budget = exports.MAX_TURN_RESULT_CHARS) {
    let spent = 0;
    let trimmed = 0;
    const out = results.map((r) => {
        const text = String(r.content ?? "");
        if (r.ok === false || spent + text.length <= budget) {
            spent += text.length;
            return r;
        }
        const room = Math.max(0, budget - spent);
        spent = budget;
        trimmed++;
        return Object.assign({}, r, {
            content: room > 400
                ? truncate(text, room, "this result")
                : "[... omitted: this turn's tool output reached its budget of " + budget +
                    " characters. Read fewer files at once, or use search_code.]"
        });
    });
    return { results: out, trimmed };
}
